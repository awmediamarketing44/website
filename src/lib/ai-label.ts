function findSourceType(s: string): string | null {
  let m = s.match(/digitalsourcetype\/([A-Za-z]+)/i);
  if (m) return m[1];
  m = s.match(/DigitalSourceType["'>\s]+([A-Za-z]+)/i);
  return m ? m[1] : null;
}

function findXmpTag(s: string, tag: string): string | null {
  let m = s.match(new RegExp(`<[A-Za-z0-9]+:${tag}>([^<]{1,200})</`, "i"));
  if (m) return m[1].trim();
  m = s.match(new RegExp(`[A-Za-z0-9]+:${tag}="([^"]{1,200})"`, "i"));
  return m ? m[1].trim() : null;
}

interface C2paInfo {
  present: boolean;
  generator: string | null;
  sourceType: string | null;
  actions: string[];
}

/**
 * Read a CBOR text string at `pos`. Major type 3: 0x60|len for len < 24,
 * 0x78 + 1 length byte, 0x79 + 2 length bytes. Enough for the short label
 * strings we want; anything else we treat as absent.
 */
function cborTextAt(buf: string, pos: number): string | null {
  const b = buf.charCodeAt(pos);
  let len: number;
  let start: number;

  if (b >= 0x60 && b <= 0x77) {
    len = b - 0x60;
    start = pos + 1;
  } else if (b === 0x78) {
    len = buf.charCodeAt(pos + 1);
    start = pos + 2;
  } else if (b === 0x79) {
    len = (buf.charCodeAt(pos + 1) << 8) | buf.charCodeAt(pos + 2);
    start = pos + 3;
  } else {
    return null;
  }

  if (!Number.isFinite(len) || len < 1 || len > 200) return null;
  const s = buf.slice(start, start + len);
  // Reject anything non-printable: we mis-read the offset if that happens.
  return /^[\x20-\x7E]+$/.test(s) ? s : null;
}

/** Find a CBOR map key by name, then read the text value that follows it. */
function cborTextAfterKey(buf: string, key: string, from = 0): string | null {
  const i = buf.indexOf(key, from);
  return i === -1 ? null : cborTextAt(buf, i + key.length);
}

/**
 * Pull a human-readable generator name out of the manifest.
 *
 * C2PA v2 uses `claim_generator_info`, a map of name + version. Note that a
 * naive search for `claim_generator` prefix-matches that key and reads back
 * "info", so the v2 form has to be tried FIRST.
 */
function extractGenerator(joined: string): string | null {
  // Collect both: claim_generator_info names the product ("OpenAI Media
  // Service API") while softwareAgent names the actual model ("gpt-image 2.0").
  // The model is the useful half for spotting which tool did it.
  const parts: string[] = [];
  for (const anchor of ["claim_generator_info", "softwareAgent"]) {
    const i = joined.indexOf(anchor);
    if (i === -1) continue;
    const name = cborTextAfterKey(joined, "name", i);
    if (!name) continue;
    const version = cborTextAfterKey(joined, "version", i);
    const s = version ? `${name} ${version}` : name;
    if (!parts.includes(s)) parts.push(s);
  }
  if (parts.length) return parts.join(" / ");

  // C2PA v1: claim_generator is a plain string.
  const v1 = cborTextAfterKey(joined, "claim_generator");
  return v1 && !v1.startsWith("info") ? v1 : null;
}

/**
 * C2PA manifests are CBOR inside JUMBF. We do not decode the whole structure —
 * the strings we want sit in the payload as readable UTF-8, so a targeted read
 * gets them.
 */
function readC2pa(blobs: string[]): C2paInfo {
  const joined = blobs.join("\n");
  const out: C2paInfo = {
    present: false,
    generator: null,
    sourceType: null,
    actions: [],
  };
  if (!joined) return out;

  out.present = joined.includes("c2pa") || joined.includes("jumd");
  if (!out.present) return out;

  out.generator = extractGenerator(joined);
  out.sourceType = findSourceType(joined);

  for (const a of [
    "c2pa.created",
    "c2pa.edited",
    "c2pa.placed",
    "c2pa.opened",
    "c2pa.converted",
    "c2pa.published",
  ]) {
    if (joined.includes(a)) out.actions.push(a);
  }
  return out;
}

function matchTools(haystack: string): { name: string; ai: boolean }[] {
  const h = haystack.toLowerCase();
  return TOOL_SIGNATURES.filter((s) => h.includes(s.needle)).map((s) => ({
    name: s.name,
    ai: s.ai,
  }));
}

