// ---------------------------------------------------------------------------
// Container walkers. All of this parses hostile input, so bounds-check hard.
// ---------------------------------------------------------------------------

interface Bag {
  xmp: string[];
  exif: Buffer[];
  c2pa: string[];
  text: string[];
}

const newBag = (): Bag => ({ xmp: [], exif: [], c2pa: [], text: [] });

function walkJpeg(b: Buffer, bag: Bag): Bag {
  const len = b.length;
  let i = 2; // skip FFD8

  while (i + 4 <= len) {
    if (b[i] !== 0xff) {
      i++;
      continue;
    }
    const marker = b[i + 1];
    if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
      i += 2;
      continue;
    }
    if (marker === 0xda || marker === 0xd9) break; // start of scan / end of image

    const seglen = b.readUInt16BE(i + 2);
    if (seglen < 2 || i + 2 + seglen > len) break;
    const data = b.subarray(i + 4, i + 2 + seglen);

    if (marker === 0xe1) {
      const head = data.subarray(0, 80).toString("latin1");
      if (head.startsWith("Exif\0\0")) {
        bag.exif.push(data.subarray(6));
      } else if (head.includes("ns.adobe.com/xap/1.0/")) {
        const nul = data.indexOf(0);
        bag.xmp.push(data.subarray(nul === -1 ? 0 : nul + 1).toString("utf8"));
      } else if (head.includes("ns.adobe.com/xmp/extension/")) {
        bag.xmp.push(data.toString("utf8"));
      }
    } else if (marker === 0xeb) {
      bag.c2pa.push(data.toString("latin1")); // APP11 JUMBF, carries C2PA
    } else if (marker === 0xed) {
      bag.text.push(data.toString("latin1")); // APP13 Photoshop IRB / legacy IPTC
    }

    i += 2 + seglen;
  }
  return bag;
}

function walkPng(b: Buffer, bag: Bag): Bag {
  const len = b.length;
  let i = 8; // skip signature

  while (i + 8 <= len) {
    const clen = b.readUInt32BE(i);
    const type = b.subarray(i + 4, i + 8).toString("latin1");
    if (clen < 0 || i + 12 + clen > len) break;
    const data = b.subarray(i + 8, i + 8 + clen);

    if (type === "iTXt") {
      // keyword \0 compFlag compMethod lang \0 translated \0 text
      const p = data.indexOf(0);
      if (p !== -1) {
        const keyword = data.subarray(0, p).toString("latin1");
        const compFlag = data[p + 1] ?? 0;
        const rest = data.subarray(p + 3);
        const q = rest.indexOf(0);
        const r = q === -1 ? -1 : rest.indexOf(0, q + 1);
        let text = r === -1 ? Buffer.alloc(0) : rest.subarray(r + 1);
        if (compFlag === 1 && text.length) {
          try {
            text = inflateSync(text);
          } catch {
            text = Buffer.alloc(0);
          }
        }
        if (text.length) {
          const s = text.toString("utf8");
          if (/xmp/i.test(keyword)) bag.xmp.push(s);
          else bag.text.push(`${keyword}: ${s}`);
        }
      }
    } else if (type === "tEXt") {
      const p = data.indexOf(0);
      if (p !== -1) {
        bag.text.push(
          `${data.subarray(0, p).toString("latin1")}: ${data.subarray(p + 1).toString("latin1")}`,
        );
      }
    } else if (type === "zTXt") {
      const p = data.indexOf(0);
      if (p !== -1) {
        try {
          bag.text.push(
            `${data.subarray(0, p).toString("latin1")}: ${inflateSync(data.subarray(p + 2)).toString("utf8")}`,
          );
        } catch {
          /* corrupt chunk, skip */
        }
      }
    } else if (type === "eXIf") {
      bag.exif.push(Buffer.from(data));
    } else if (type === "caBX") {
      bag.c2pa.push(data.toString("latin1")); // C2PA in PNG
    }

    if (type === "IEND") break;
    i += 12 + clen;
  }
  return bag;
}

function walkWebp(b: Buffer, bag: Bag): Bag {
  const len = b.length;
  let i = 12; // RIFF____WEBP

  while (i + 8 <= len) {
    const fourcc = b.subarray(i, i + 4).toString("latin1");
    const clen = b.readUInt32LE(i + 4);
    if (clen < 0 || i + 8 + clen > len) break;
    const data = b.subarray(i + 8, i + 8 + clen);

    if (fourcc === "XMP ") bag.xmp.push(data.toString("utf8"));
    else if (fourcc === "EXIF") {
      bag.exif.push(
        Buffer.from(
          data.subarray(0, 6).toString("latin1") === "Exif\0\0" ? data.subarray(6) : data,
        ),
      );
    } else if (fourcc === "C2PA") bag.c2pa.push(data.toString("latin1"));

    i += 8 + clen + (clen % 2); // chunks are even-padded
  }
  return bag;
}

// ---------------------------------------------------------------------------
// EXIF: minimal TIFF IFD walker. We only want Make, Model and Software.
// ---------------------------------------------------------------------------

function readExif(t: Buffer): Record<string, string> {
  const out: Record<string, string> = {};
  if (t.length < 8) return out;

  const bo = t.subarray(0, 2).toString("latin1");
  if (bo !== "II" && bo !== "MM") return out;
  const le = bo === "II";

  const u16 = (o: number) =>
    t.length >= o + 2 ? (le ? t.readUInt16LE(o) : t.readUInt16BE(o)) : 0;
  const u32 = (o: number) =>
    t.length >= o + 4 ? (le ? t.readUInt32LE(o) : t.readUInt32BE(o)) : 0;

  if (u16(2) !== 42) return out;
  const ifd = u32(4);
  if (ifd < 8 || ifd + 2 > t.length) return out;

  const count = u16(ifd);
  if (count > 512) return out; // sanity guard on malformed input

  const wanted: Record<number, string> = {
    0x010f: "make",
    0x0110: "model",
    0x0131: "software",
  };

  for (let n = 0; n < count; n++) {
    const e = ifd + 2 + n * 12;
    if (e + 12 > t.length) break;

    const tag = u16(e);
    if (!wanted[tag]) continue;
    if (u16(e + 2) !== 2) continue; // ASCII only

    const cnt = u32(e + 4);
    if (cnt < 1 || cnt > 4096) continue;

    const start = cnt <= 4 ? e + 8 : u32(e + 8);
    if (start + cnt > t.length) continue;

    const val = t
      .subarray(start, start + cnt)
      .toString("latin1")
      .replace(/\0/g, "")
      .trim();
    if (val) out[wanted[tag]] = val;
  }
  return out;
}

