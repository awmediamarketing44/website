// AI Label Checker — image provenance / metadata parser.
//
// Reads the metadata that social platforms actually use to decide whether to
// stamp an "AI info" badge on a post:
//
//   1. IPTC DigitalSourceType   (in the XMP packet)  — what Instagram reads
//   2. C2PA Content Credentials (JUMBF / caBX box)   — what LinkedIn + TikTok read
//   3. EXIF Software / XMP CreatorTool               — which tool wrote the file
//   4. EXIF Make / Model                             — evidence of a real camera
//
// Dependency-free byte walking. No sharp, no exiftool, no c2patool.
//
// TWO LIMITATIONS, and the UI must state both:
//   - We detect the PRESENCE and readable claims of a C2PA manifest. We do NOT
//     verify its cryptographic signature.
//   - No metadata check can predict a platform's own image classifier, which
//     runs on top of all of this.
//
// NOTE: the PLATFORM_READS matrix below is mirrored in the portal's PHP copy at
// `AW PORTAL/includes/ai-label.php` (ail_platforms). Platforms change what they
// read. When you update one, update the other.

import { inflateSync } from "zlib";

export const AIL_MAX_BYTES = 25 * 1024 * 1024;

/**
 * label    — the platform reads a tag this file carries, and that tag declares AI.
 * possible — the file declares AI, but via a tag THIS platform does not read.
 *            Metadata will not trigger it, but the platform's own classifier might.
 * clear    — nothing in the file declares AI at all.
 */
export type Verdict = "label" | "possible" | "clear";

